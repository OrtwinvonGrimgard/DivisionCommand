// Regenerates web/js/data/image-manifest.js from the real files under web/assets/cards.
const fs = require('fs'), path = require('path');
const WEB = path.join(__dirname, '../../Division_Command/web');
const ROOT = path.join(WEB, 'assets/cards');
/**
 * Durchläuft ein Verzeichnis rekursiv und sammelt Bilddateien für das Manifest.
 */
function walk(d) { return fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]); }
const files = walk(ROOT).map(f => path.relative(ROOT, f).split(path.sep).join('/')).filter(f => /\.(png|jpe?g|webp)$/i.test(f)).sort();
const out = '// Generated by scripts/build/build_image_manifest.js. Exact card image files (relative to assets/cards).\nwindow.DC_CARD_FILES = ' + JSON.stringify(files) + ';\n';
fs.writeFileSync(path.join(WEB, 'js/data/image-manifest.js'), out);
if (require.main === module) console.log('manifest', files.length);
module.exports = { files };
