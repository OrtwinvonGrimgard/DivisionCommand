#!/usr/bin/env python3
"""t212 Vorderseiten-Build (gfx2): jede ID mit echtem Motiv -> faces-v2/<id>.webp im Originalrahmen
(face.py, KartenEditor-Renderer). Flächentext = scripts/cards-review/kurz.json (<=120 Zeichen) + Schlüsselwort-Chips;
Volltext bleibt in `text` (Detailansicht) und docs/regeln/KARTEN_SONDERFAELLE.md. Ohne Motiv kein Gesicht
(ehrlich offen in missing-illustrations.json). Aufruf: python3 render.py [--only id,id] [--jobs 4]"""
from __future__ import annotations
import argparse, hashlib, json, subprocess, sys
from pathlib import Path
from concurrent.futures import ProcessPoolExecutor, as_completed
ROOT = Path(__file__).resolve().parents[2]; WEB = ROOT / 'Division_Command_0.5a/web'; HERE = Path(__file__).resolve().parent
VERSION = 'gfx2'; OUTDIR = 'faces-v2'
def digest(b): return hashlib.sha256(b).hexdigest()
def src_sha(c): return digest(json.dumps(c, ensure_ascii=False, sort_keys=True).encode())
def catalog():
    return json.loads(subprocess.check_output(['node', str(HERE / 'export_catalog.js')], cwd=ROOT))
def art_for(ident, data):
    for sub in ('art-v2', 'art-v1'):
        p = WEB / 'assets/cards' / sub / (ident + '.jpg')
        if p.is_file(): return p, ('generated_art' if sub == 'art-v2' else 'generated_art_v1')
    rec = data['art'].get(ident)
    if rec and rec['kind'] == 'artwork': return WEB / rec['src'], 'existing_art'
    return None, None
def job(c, art, kurz, number):
    sys.path.insert(0, str(HERE)); import face
    dest = WEB / 'assets/cards' / OUTDIR / (c['id'] + '.webp')
    if c['typ'] == 'Doktrin': lay = face.render_doctrine(c, kurz, str(dest), number=number)
    else: lay = face.render(c, str(art), kurz, c.get('keywords') or [], str(dest), number=number)
    return c['id'], {k: lay[k] for k in ('art_box', 'panel') if k in lay}
def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--only'); ap.add_argument('--jobs', type=int, default=4); a = ap.parse_args()
    data = catalog(); K = json.loads((ROOT / 'scripts/cards-review/kurz.json').read_text())
    mp = HERE / 'graphics-manifest.json'
    old = {r['id']: r for r in json.loads(mp.read_text()).get('records', [])} if mp.is_file() and json.loads(mp.read_text()).get('version') == VERSION else {}
    only = set(a.only.split(',')) if a.only else None
    recs, todo = [], []
    for n, c in enumerate(data['cards'], 1):
        i = c['id']; art, prov = art_for(i, data)
        if c['typ'] == 'Doktrin': prov = 'doctrine_design'
        if c['typ'] == 'Token': prov = 'special_token'
        r = {'id': i, 'name': c['name'], 'type': c['typ'], 'nation': c.get('nation') or 'neutral', 'rarity': c.get('rarity'),
             'source_record_sha256': src_sha(c), 'kurz': K[i]['kurz'], 'keywords': c.get('keywords') or [],
             'printed_stats': {'ap': c.get('ap'), 'atk': c.get('atk'), 'def': c.get('def'), 'tags': c.get('tags', [])},
             'art': str(art.relative_to(WEB)) if art else None, 'art_sha256': digest(art.read_bytes()) if art else None,
             'provenance': prov or 'missing_illustration', 'ready': False, 'output': None}
        if prov in ('existing_art', 'generated_art', 'generated_art_v1', 'doctrine_design'):
            r['ready'] = True; r['output'] = OUTDIR + '/' + i + '.webp'
            o = old.get(i); dest = WEB / 'assets/cards' / r['output']
            fresh = o and dest.is_file() and o.get('source_record_sha256') == r['source_record_sha256'] and o.get('kurz') == r['kurz'] and o.get('art_sha256') == r['art_sha256'] and o.get('renderer') == digest((HERE / 'face.py').read_bytes())
            if (only is None and not fresh) or (only and i in only): todo.append((c, art, K[i]['kurz'], str(n).zfill(3)))
            elif o: r['layout'] = o.get('layout')
        recs.append(r)
    print('render', len(todo), 'faces')
    lay = {}
    with ProcessPoolExecutor(a.jobs) as ex:
        for f in as_completed([ex.submit(job, *t) for t in todo]):
            i, l = f.result(); lay[i] = l
    rd = digest((HERE / 'face.py').read_bytes())
    for r in recs:
        if r['id'] in lay: r['layout'] = lay[r['id']]
        if r['ready']:
            r['renderer'] = rd; r['output_sha256'] = digest((WEB / 'assets/cards' / r['output']).read_bytes())
    missing = [r['id'] for r in recs if r['provenance'] == 'missing_illustration']
    m = {'version': VERSION, 'catalog_ids': len(recs), 'new_faces': sum(r['ready'] for r in recs), 'missing_illustrations': missing,
         'complete': not missing, 'records': recs}
    mp.write_text(json.dumps(m, ensure_ascii=False, indent=1) + '\n')
    runtime = {r['id']: {'file': r['output'], 'art': {'kind': 'artwork', 'src': r['art']} if r['art'] else None} for r in recs if r['ready']}
    (WEB / 'js/data/card-faces.js').write_text('// Generated by scripts/graphics/render.py (gfx2): ready faces only. Rule records unchanged.\nwindow.DC_CARD_FACES = ' + json.dumps(runtime, ensure_ascii=False, separators=(',', ':')) + ';\nwindow.dcCardImage = function(def) { var ready=def && window.DC_CARD_FACES[def.id]; return ready ? ready.file : (def && def.image) || ""; };\n')
    C = {c['id']: c for c in data['cards']}
    cards = [{k: C[i].get(k) for k in ('id', 'name', 'typ', 'nation', 'rarity', 'klasse', 'tags', 'ap', 'atk', 'def', 'text', 'flavor')} for i in missing]
    (HERE / 'missing-illustrations.json').write_text(json.dumps({'remaining_count': len(missing), 'done_generated': sum(1 for r in recs if r['provenance'] == 'generated_art'), 'cards': cards}, ensure_ascii=False, indent=1) + '\n')
    print('faces', m['new_faces'], 'missing', len(missing))
if __name__ == '__main__': main()
